<h1>可观测与工作台</h1>

<p class="lead">
	每个请求从进来、选路、一次次尝试到结束，网关都会记下来，正在进行的请求还能实时看到。工作台用来不经过客户端直接测渠道和模型。
</p>

<Heading id="overview">总览</Heading>

<p>
	「总览」页显示正在进行的请求、请求数和成功率的趋势、Token 用量、首字时间，以及按渠道、下发模型和 API 密钥统计的费用。统计按小时汇总，汇总永久保留，不受请求记录保留期影响。
</p>

<Heading id="requests">请求日志</Heading>

<p>「请求日志」页列出每个请求，上面是正在进行的，下面是已经结束的。每一行有下发模型、API 密钥、结果、首字时间、耗时、用量和费用。</p>

<ul>
	<li>
		<strong>筛选</strong>：按下发模型、结果、API 密钥、来源（客户端或工作台）、类型和渠道。筛选条件写在地址里，可以收藏或分享。渠道页和下发模型页的「看它的请求」直接带上筛选。
	</li>
	<li>
		<strong>请求详情</strong>：点进去能看到每一次尝试落在哪个渠道、上游模型和渠道密钥，失败的原因和 HTTP 状态，有没有经过转换，冷却了什么；选路时哪些候选被跳过、为什么；亲和的结果；用量和费用的明细。
	</li>
	<li>
		<strong>保留期</strong>：请求记录默认保留 7 天，见<a href={resolve('/configuration') + '#traffic'}>配置参考</a>。
	</li>
</ul>

<Heading id="interrupt" level={3}>中断</Heading>

<p>
	正在进行的请求可以在请求日志里中断。客户端收到错误，网关不换渠道重试，不计入健康度也不触发冷却；已经产生的用量照样计费。
</p>

<Heading id="debug-capture">调试原文</Heading>

<p>想看客户端和上游之间到底传了什么，就开调试原文。全局（「设置」页）、渠道和 API 密钥各有一个开关，任一开着就录。</p>

<ul>
	<li>每次尝试存三份：客户端的原始请求、发给上游的请求和上游的响应（流式存原始 SSE），每份最多 1 MB。</li>
	<li>认证头和含已知密钥的请求头会打码，正文原样保存，所以里面可能有用户的对话内容。</li>
	<li>开关默认关。打开时要给时长，默认 1 小时，最长 24 小时，到点自动关。</li>
	<li>
		原文存在单独的 <code>ntm-debug.db</code>，保留 24 小时。写盘跟不上时丢原文，不拖慢转发，丢了多少在「设置」页显示。
	</li>
	<li>在请求详情里查看原文。</li>
</ul>

<Heading id="workbench">工作台</Heading>

<p>「工作台」页有三种测法：</p>

<ul>
	<li>
		<strong>渠道测试</strong>：固定到一个渠道，不走选路，用渠道自己的格式透传。可以选一把渠道密钥，停用的渠道和密钥也能测。可用时段、每日上限、RPM、并发和模型白名单都不拦，冷却中的密钥照样发，成功就清掉这次证明可用的冷却。适合充值或换了密钥后验证一下。渠道页有链接直接打开。
	</li>
	<li>
		<strong>模型测试</strong>：按下发模型正常选路，可以选入站格式，看请求落在哪个候选上、换过几次。照常遵守渠道的限制。嵌入和图片类型的下发模型也能测。
	</li>
	<li>
		<strong>对话</strong>：多轮对话，目标可以是「渠道 + 上游模型」或下发模型。支持上传图片、思考强度（关、低、中、高）、内置搜索和生图，请求体可以展开改原始 JSON。生图走对话格式：Responses
		的 <code>image_generation</code> 工具，或 Chat 的 <code>modalities</code>（Gemini、OpenRouter 的写法）；Anthropic 不能生图。对话只存在页面里，刷新就没了。
	</li>
</ul>

<p>
	工作台的请求记在请求日志里，来源标成「工作台」，费用计入渠道的每日费用，不属于任何 API 密钥。它们失败不进冷却，也不影响健康度，而且一律录调试原文（<a
		href={adr('0017-workbench-request-side-effects.md')}>ADR-0017</a
	>）。
</p>
